import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { startService } from '../src/service.js';
import { ServiceClient } from '../src/client.js';
import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { StdioClientTransport } from '@modelcontextprotocol/sdk/client/stdio.js';
const tick=()=>new Promise(r=>setImmediate(r));
test('two MCP facades share durable jobs; disconnect never cancels; service restart preserves results',{skip:process.platform==='win32'},async t=>{
 const directory=mkdtempSync(join(tmpdir(),'bridge-http-'));let finish;
 const runner=async()=>new Promise(r=>finish=()=>r({status:'completed',result:'survived'}));
 let service=await startService({directory,runner,resolveProject:async cwd=>({cwd,project:cwd})});
 t.after(async()=>{finish?.();await service.close();rmSync(directory,{recursive:true,force:true});});
 await assert.rejects(startService({directory,runner}),/already running/);
 const connect=async()=>{const client=new Client({name:'test',version:'1'});await client.connect(new StdioClientTransport({command:process.execPath,args:[resolve('src/mcp-client.js')],env:{...process.env,BRIDGE_STATE_DIR:directory,BRIDGE_CLIENT:'codex'},stderr:'pipe'}));return client;};
 const one=await connect(),two=await connect();t.after(()=>two.close());
 const call=async(c,name,args)=>{const r=await c.callTool({name,arguments:args});assert.ok(!r.isError,r.content[0].text);return JSON.parse(r.content[0].text);};
 const job=await call(one,'claude_start',{prompt:'hello',cwd:'/tmp',requestId:'test-retry'});
 await one.close();
 assert.equal((await call(two,'claude_status',{jobId:job.id})).status,'running');
 assert.equal((await call(two,'claude_start',{prompt:'hello',cwd:'/tmp',requestId:'test-retry'})).id,job.id);
 finish();await tick();
 assert.equal((await call(two,'claude_status',{jobId:job.id})).result,'survived');
 await two.close();await service.close();
 service=await startService({directory,runner});
 const fresh=new ServiceClient({directory});
 assert.equal((await fresh.call('claude','status',{jobId:job.id})).result,'survived');
 await assert.rejects(fresh.call('codex','status',{jobId:job.id}),/not found/);
 await assert.rejects(fresh.call('claude','list_jobs',{limit:101}),/limit/);
 await assert.rejects(fresh.call('claude','status',{jobId:job.id,extra:true}),/argument/);
 await assert.rejects(fresh.call('claude','start',{prompt:'x'.repeat(600000),cwd:'/tmp'}),/large|size|prompt/);
});
test('transport retry keeps one requestId when response is lost',{skip:process.platform==='win32'},async t=>{
 const directory=mkdtempSync(join(tmpdir(),'bridge-retry-'));
 const service=await startService({directory,runner:async()=>({status:'completed',result:'once'}),resolveProject:async cwd=>({cwd,project:cwd})});
 t.after(async()=>{await service.close();rmSync(directory,{recursive:true,force:true});});
 const client=new ServiceClient({directory});const original=client.request.bind(client);let lost=true;
 client.request=async body=>{const result=await original(body);if(lost){lost=false;throw Object.assign(Error('connection lost'),{code:'ECONNRESET'});}return result;};
 const job=await client.call('claude','start',{prompt:'hello',cwd:'/tmp'});await tick();
 assert.equal((await client.call('claude','list_jobs',{})).jobs.length,1);
 assert.equal((await client.call('claude','status',{jobId:job.id})).result,'once');
});
